"""rewrite the readme results block from reports/summary.json so published numbers always match the report."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from incidentforge.report import CAUSE_LABELS, CAUSES

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- results:start (generated by scripts/readme_results.py from reports/summary.json) -->"
END = "<!-- results:end -->"


def _pct(x: Any) -> str:
    return f"{float(x):.0%}"


def _dataset_rows(block: dict[str, Any]) -> list[tuple[str, str]]:
    v = block.get("validation") or {}
    fams = block.get("tasks_by_family") or {}
    rows = [("Tasks in the dataset", f"{block.get('tasks_total', 0)} across {len(fams)} families")]
    if v.get("candidates") and "passed_gates" in v:
        rows.append(("Generated candidates", str(v["candidates"])))
        rows.append(("Passing every gate", f"{v['passed_gates']} of {v['candidates']}"))
        dropped = len(v.get("dropped") or [])
        rows.append(
            ("Kept in the dataset", f"{v.get('accepted', 0)}" + (f" ({dropped} dropped on review)" if dropped else ""))
        )
    elif v.get("candidates"):
        rows.append(("Candidates passing every gate", f"{v.get('accepted', 0)} of {v['candidates']}"))
    if v.get("mutants_total"):
        killed, total = v.get("mutants_killed", 0), v["mutants_total"]
        rows.append(("Mutants killed by accepted tasks' tests", f"{killed} of {total} ({_pct(killed / total)})"))
    hm = block.get("harbor_matrix")
    if hm:
        version = f" (Harbor {hm['harbor_version']})" if hm.get("harbor_version") else ""
        rows.append(("No-op agent scores 0.0", f"{hm['nop']['ok']} of {hm['nop']['total']}{version}"))
        rows.append(("Oracle agent scores 1.0", f"{hm['oracle']['ok']} of {hm['oracle']['total']}{version}"))
    return rows


def _primary(name: str, block: dict[str, Any], generated_at: str) -> list[str]:
    out = ["| | Value |", "|---|---|"]
    out += [f"| {k} | {val} |" for k, val in _dataset_rows(block)]
    models = block.get("models") or []
    if models:
        out += [
            "",
            f"Models on the {name} tasks (pass rate = share of runs with reward 1.0; mean reward also counts "
            "partial credit):",
            "",
            "| Model | Agent | Runs | Pass rate | Mean reward |",
            "|---|---|---|---|---|",
        ]
        out += [
            f"| {m.get('label', m.get('model'))} | {m.get('agent')} | {m.get('n')} (k={m.get('k')}) "
            f"| {_pct(m.get('pass_rate', 0))} | {float(m.get('mean_reward', m.get('pass_rate', 0))):.2f} |"
            for m in sorted(models, key=lambda m: (-float(m.get("pass_rate", 0)), -float(m.get("mean_reward", 0))))
        ]
    causes = (block.get("failure_causes") or {}).get("by_model") or {}
    if causes:
        keys = list(CAUSES)
        out += ["", "Why failed runs failed (one cause per run):", ""]
        out += ["| Model | " + " | ".join(CAUSE_LABELS[k].capitalize() for k in keys) + " |"]
        out += ["|---|" + "---|" * len(keys)]
        out += [f"| {m} | " + " | ".join(str(c.get(k, 0)) for k in keys) + " |" for m, c in sorted(causes.items())]
    findings = block.get("findings") or []
    if findings:
        out += ["", "Findings:", ""] + [f"- {f}" for f in findings]
    out += ["", f"Generated {generated_at}. Full per-family breakdown: `reports/index.html`."]
    return out


def render(summary: dict[str, Any]) -> str:
    bt = summary.get("by_target") or {}
    primary = bt.get("primary")
    if primary and primary in bt:
        body = _primary(primary, bt[primary], summary.get("generated_at", ""))
        return "\n".join([START, "", *body, END])
    out = [START, "", "| | Value |", "|---|---|"]
    out += [f"| {k} | {val} |" for k, val in _dataset_rows(summary)]
    models = summary.get("models") or []
    if models:
        out += ["", "| Model | Agent | Runs | Pass rate |", "|---|---|---|---|"]
        out += [
            f"| {m.get('model')} | {m.get('agent')} | {m.get('n')} (up to k={m.get('k')} per task) "
            f"| {_pct(m.get('pass_rate', 0))} |"
            for m in sorted(models, key=lambda m: -float(m.get("pass_rate", 0)))
        ]
    failures = summary.get("failures") or {}
    if failures:
        out += ["", "Where failed runs break (failing test kinds per model):", ""]
        out += ["| Model | Fault-injection tests | Happy-path tests | Repo suite |", "|---|---|---|---|"]
        out += [
            f"| {m} | {c.get('fault', 0)} | {c.get('happy', 0)} | {c.get('regression', 0)} |"
            for m, c in sorted(failures.items())
        ]
    findings = summary.get("findings") or []
    if findings:
        out += ["", "Findings:", ""] + [f"- {f}" for f in findings]
    out += ["", f"Generated {summary.get('generated_at', '')}. Full per-family breakdown: `reports/index.html`.", END]
    return "\n".join(out)


def update(readme: str, summary: dict[str, Any]) -> str:
    if START not in readme or END not in readme:
        raise SystemExit("readme has no results markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + render(summary) + tail


def main(summary_path: str = "reports/summary.json", readme_path: str = "README.md") -> None:
    summary = json.loads(Path(summary_path).read_text())
    path = Path(readme_path)
    path.write_text(update(path.read_text(), summary))
    print(f"{readme_path} results updated from {summary_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
