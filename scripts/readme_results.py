"""rewrite the readme results block from reports/summary.json so published numbers always match the report."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- results:start (generated by scripts/readme_results.py from reports/summary.json) -->"
END = "<!-- results:end -->"


def _pct(x: Any) -> str:
    return f"{float(x):.0%}"


def render(summary: dict[str, Any]) -> str:
    v = summary.get("validation") or {}
    fams = summary.get("tasks_by_family") or {}
    rows = [
        ("Tasks in the dataset", f"{summary.get('tasks_total', 0)} across {len(fams)} families"),
    ]
    if v.get("candidates"):
        rows.append(("Candidates passing every gate", f"{v.get('accepted', 0)} of {v['candidates']}"))
    if v.get("mutants_total"):
        killed, total = v.get("mutants_killed", 0), v["mutants_total"]
        rows.append(("Mutants killed by accepted tasks' tests", f"{killed} of {total} ({_pct(killed / total)})"))
    if "spend_usd" in summary:
        rows.append(("Paid API spend", f"${float(summary['spend_usd']):.2f} (hard cap $70)"))
    out = [START, "", "| | Value |", "|---|---|"]
    out += [f"| {k} | {val} |" for k, val in rows]
    models = summary.get("models") or []
    if models:
        out += ["", "| Model | Agent | Runs | Pass rate |", "|---|---|---|---|"]
        out += [
            f"| {m.get('model')} | {m.get('agent')} | {m.get('n')} (up to k={m.get('k')} per task) "
            f"| {_pct(m.get('pass_rate', 0))} |"
            for m in sorted(models, key=lambda m: -float(m.get("pass_rate", 0)))
        ]
    failures = summary.get("failures") or {}
    if failures:
        out += ["", "Where failed runs break (failing test kinds per model):", ""]
        out += ["| Model | Fault-injection tests | Happy-path tests | Repo suite |", "|---|---|---|---|"]
        out += [
            f"| {m} | {c.get('fault', 0)} | {c.get('happy', 0)} | {c.get('regression', 0)} |"
            for m, c in sorted(failures.items())
        ]
    findings = summary.get("findings") or []
    if findings:
        out += ["", "Findings:", ""] + [f"- {f}" for f in findings]
    out += ["", f"Generated {summary.get('generated_at', '')}. Full per-family breakdown: `reports/index.html`.", END]
    return "\n".join(out)


def update(readme: str, summary: dict[str, Any]) -> str:
    if START not in readme or END not in readme:
        raise SystemExit("readme has no results markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + render(summary) + tail


def main(summary_path: str = "reports/summary.json", readme_path: str = "README.md") -> None:
    summary = json.loads(Path(summary_path).read_text())
    path = Path(readme_path)
    path.write_text(update(path.read_text(), summary))
    print(f"{readme_path} results updated from {summary_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
